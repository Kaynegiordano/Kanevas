const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const root = process.env.KANEVAS_TEST_ROOT || path.join(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'kanevas-managed-'));
const profile = path.join(tmp, 'profile'), destination = path.join(tmp, 'data'); fs.mkdirSync(profile); fs.mkdirSync(destination);
const original = '{"data":"original","models":"shared"}'; fs.writeFileSync(path.join(profile, 'forge-dirs.json'), original);
const crypto = require('node:crypto');
const config = require(path.join(root, 'managed-runtimes.cjs'))(profile), reportFile = path.join(destination, 'migration.json');
const report = { schema: 1, source: path.join(tmp, 'source'), destination, models: path.join(tmp, 'models'), sourcesPreserved: true, profiles: [], components: {} };
for (const [id, entry] of Object.entries({ studio: 'launch.py', comfyui: 'main.py', wallpaper: 'outils/peintre.py', training: 'anima_train_network.py' })) {
  const directory = path.join(destination, 'runtimes', id), python = path.join(directory, 'venv/Scripts/python.exe');
  fs.mkdirSync(path.dirname(python), { recursive: true }); fs.writeFileSync(python, 'python');
  fs.mkdirSync(path.dirname(path.join(directory, entry)), { recursive: true }); fs.writeFileSync(path.join(directory, entry), '# fixture');
  fs.writeFileSync(path.join(directory, 'venv/pyvenv.cfg'), 'home = base-python');
  const manifest = path.join(destination, id + '-files.jsonl');
  fs.writeFileSync(manifest, [entry,'venv/Scripts/python.exe','venv/pyvenv.cfg'].map(name=>JSON.stringify({path:name,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(directory,name))).digest('hex')})).join('\n'));
  report.components[id] = { directory, python, manifest, source:path.join(report.source,id), phase: 'probed' };
  fs.mkdirSync(report.components[id].source, { recursive: true });
}
const media = path.join(destination,'bin'); fs.mkdirSync(media); const ffmpeg = path.join(media,'ffmpeg.exe'); fs.writeFileSync(ffmpeg,'fixture');
report.media = { phase:'probed',directory:media,ffmpeg,files:[{name:'ffmpeg.exe',sha256:crypto.createHash('sha256').update('fixture').digest('hex')}] };
const save = () => fs.writeFileSync(reportFile, JSON.stringify(report)); save();
assert.throws(() => config.activate(reportFile), /vérifiée/);
report.integrityCheckedAt = Date.now(); report.components.training.phase = 'verified'; save();
assert.throws(() => config.activate(reportFile), /non testé/);
report.components.training.phase = 'probed'; save();
const active = config.activate(reportFile);
assert(active.active && active.deletionAllowed === false);
const env = config.environment('studio',{PATH:path.join(report.source,'studio','venv','Scripts')+path.delimiter+'C:\\Windows',PYTHONPATH:report.source,PYTHONHOME:report.source,HF_HOME:path.join(report.source,'studio','cache')});
assert(!env.PYTHONPATH && !env.PYTHONHOME && !env.PATH.includes(path.join(report.source,'studio')) && env.IMAGEIO_FFMPEG_EXE === ffmpeg && env.HF_HOME === path.join(report.components.studio.directory,'cache'));
 assert.equal(config.directory('studio', 'legacy'), report.components.studio.directory);
assert.throws(() => config.activate(reportFile), /déjà actifs/);
fs.writeFileSync(path.join(profile, 'forge-dirs.json'), '{"data":"copied"}');
assert(!config.rollback().active); assert.equal(fs.readFileSync(path.join(profile, 'forge-dirs.json'), 'utf8'), original);
assert.equal(config.directory('studio', 'legacy'), 'legacy');
assert(fs.existsSync(report.components.studio.directory)); assert.equal(report.sourcesPreserved, true);
report.components.training.python = path.join(profile, 'external.exe'); fs.writeFileSync(report.components.training.python, 'outside'); save();
assert.throws(() => config.activate(reportFile), /Python extérieur/);
report.components.training.python = path.join(report.components.training.directory,'venv/Scripts/python.exe'); save();
fs.writeFileSync(path.join(report.components.studio.directory,'launch.py'),'changed');
assert.throws(() => config.activate(reportFile), /modifié/);
fs.writeFileSync(path.join(report.components.studio.directory,'launch.py'),'# fixture');
report.cleanup = { startedAt: Date.now(), completedAt: Date.now() }; report.sourcesPreserved = false; save();
assert(config.activate(reportFile).active);
assert.throws(() => config.rollback(), /retirées/);
assert(config.read().active, 'Le retrait des sources interdit de restaurer une configuration obsolète');
console.log('OK Activation après vérification et tests, confinement, retour exact à la configuration précédente, aucune suppression des copies');
