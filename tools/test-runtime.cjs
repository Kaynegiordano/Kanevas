const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const root = process.env.KANEVAS_TEST_ROOT || path.join(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'kanevas-runtime-'));
const config = require(path.join(root, 'studio-runtime.cjs'))(path.join(tmp, 'profile'));
const base = { data: path.join(tmp, 'old-forge'), models: path.join(tmp, 'models'), root: tmp };
assert.equal(config.resolve(base).runtime, base.data);
assert.equal(config.resolve(base).shareExternal, true);
const runtime = path.join(tmp, 'standalone-studio'); fs.mkdirSync(path.join(runtime, 'venv', 'Scripts'), { recursive: true });
fs.writeFileSync(path.join(runtime, 'venv', 'Scripts', 'python.exe'), 'test'); fs.writeFileSync(path.join(runtime, 'launch.py'), '# test'); fs.mkdirSync(base.models);
const saved = config.save({ directory: runtime, models: base.models, shareExternal: false }, base);
assert.equal(saved.runtime, runtime); assert.equal(saved.python, path.join(runtime, 'venv', 'Scripts', 'python.exe')); assert.equal(saved.root, tmp); assert.equal(saved.shareExternal, false);
assert.equal(require(path.join(root, 'studio-runtime.cjs'))(path.join(tmp, 'profile')).resolve(base).runtime, runtime);
assert.throws(() => config.save({ directory: path.join(tmp, 'missing') }, base));
assert.equal(config.resolve(base).runtime, runtime);
const { matches } = require(path.join(root, 'local-process.cjs'));
assert(matches('"C:\\KaneOS\\ComfyUI\\venv\\Scripts\\python.exe" "C:\\KaneOS\\ComfyUI\\main.py" --port 8188', 'C:\\KaneOS\\ComfyUI\\main.py'));
assert(!matches('python.exe C:\\KaneOS\\ComfyUI\\main.py.bak --port 8188', 'C:\\KaneOS\\ComfyUI\\main.py'));
assert(!matches('python.exe C:\\OtherApp\\main.py --port 8188', 'C:\\KaneOS\\ComfyUI\\main.py'));
assert(matches('C:\\KaneOS\\Forge\\venv\\Scripts\\python.exe launch.py', 'C:\\KaneOS\\Forge\\launch.py', 'C:\\KaneOS\\Forge\\venv\\Scripts\\python.exe'));
assert(!matches('C:\\OtherApp\\python.exe launch.py', 'C:\\KaneOS\\Forge\\launch.py', 'C:\\KaneOS\\Forge\\venv\\Scripts\\python.exe'));
console.log('OK Configuration autonome persistante, validation des dossiers et identification précise des processus à arrêter');
